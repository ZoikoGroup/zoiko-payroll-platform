def keyed(code: str, *parts) -> str:
    """keyed(TABLE_EMPTY, "paye_main_method") -> "NZ_TABLE_EMPTY:paye_main_method"."""
    return ":".join([code, *(str(p) for p in parts)]) if parts else code
