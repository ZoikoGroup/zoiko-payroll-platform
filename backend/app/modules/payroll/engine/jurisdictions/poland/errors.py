"""Poland calculation errors and reason codes (ZP-PL-ENG-001, PL-022).

A block code is the ``key`` of PLCalculationBlockedError; keyed() adds detail
after a colon (``PL_ROW_MISSING:pl_zus_annual_cap``). Exception codes are not
blocks: they ride on ``pl_result["exceptions"]`` and stop run APPROVAL in
Phase 4 (spec §12 payroll preflight).
"""
from app.modules.payroll.engine.countries.shared import MissingComplianceConfigurationError

_COUNTRY = "PL"


class PLCalculationBlockedError(MissingComplianceConfigurationError):
    """A Polish statutory calculation that must not proceed — missing configured
    row, missing or contradictory fact, or an unsupported case. A
    MissingComplianceConfigurationError, so the existing
    MISSING_COMPLIANCE_CONFIGURATION 400 handler applies unchanged."""

    def __init__(self, key: str, reason: str, organization_id: int = None):
        super().__init__(key, _COUNTRY, organization_id)
        self.reason = reason
        self.args = (f"Poland calculation blocked ({key}): {reason}",)


def keyed(code: str, detail) -> str:
    return f"{code}:{detail}"


