"""
engine/jurisdictions/singapore/statutory_summary.py
---------------------------------------------------
Super Admin Singapore statutory configuration summary (Phase 5.6) and the
Singapore report-template catalog. Pure: service.py gathers the facts
(packs, rows, evidence, PWM schedule statistics, templates) and this module
only arranges them into sections. No value here is a statutory rate — every
figure in the output is a persisted row value passed in by the caller; a
missing row is reported as NOT_CONFIGURED, never defaulted.

Report-template classification (ReportTemplate has no classification
column; this catalog is the single source for it, used by the summary API,
the seed script and the tests):
  EXPORT_READY        - a file/extract built to a published layout, which
                        the employer submits itself (IR8A AIS extract, CPF
                        EZPay FTP file). Not a submission, not an approval.
  SUBMISSION_SUPPORT  - figures the employer keys into / reconciles against
                        an official channel (SDL, CPF, SHG totals).
  INTERNAL_REPORT     - operational payroll report (register, summary, levy
                        reconciliation); no official format exists or is claimed.
  STATUTORY_WORKSPACE - internal compliance working view (PWM, LQS, IR21)
                        generated by a dedicated Singapore generator from
                        the existing evaluators (Phase 5.7); the generic
                        payslip-column generator refuses these types.
None of them is certified or approved by CPF Board, IRAS, MOM or PDPC
(`officialCertification` is False for every entry).
"""

