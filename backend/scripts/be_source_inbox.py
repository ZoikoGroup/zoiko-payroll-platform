"""
scripts/be_source_inbox.py
--------------------------
Belgium (ZP-BE-ENG-001 Block F3): register the official documents saved in
docs/belgium/sources/inbox/ — rerun whenever new files arrive.

  * every file (README and *.meta.txt excluded) is hashed (SHA-256) and listed in
    docs/belgium/sources/INBOX_MANIFEST.md with its size, DOWNLOAD_LIST id and the
    "official" flag from its optional <file>.meta.txt (list-id / official / retrieved);
  * with --register (local / isolated database only, _local_db_guard), each file is
    recorded as a SourceArtifact (form_number ZP-BE-SRC-<first 12 hex of the hash>)
    with its checksum and file path; it counts as ARCHIVED (checksum + file) only when
    its meta says official: yes — otherwise the title is marked [UNVERIFIED]. A
    Super Admin other than the uploader still has to review it before it can sign.

Values are not guessed from files: the extraction into the workbook is a reviewed
step (page / section reference per value) recorded in PROGRESS.md.

Usage:  python -m scripts.be_source_inbox [--register]
"""
import argparse
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

ROOT = Path(__file__).resolve().parents[2]
INBOX = ROOT / "docs" / "belgium" / "sources" / "inbox"
MANIFEST = ROOT / "docs" / "belgium" / "sources" / "INBOX_MANIFEST.md"


def be_inbox_files(inbox: Path = INBOX) -> list:
    """[{name, size, sha256, listId, official, retrieved}] for every document."""
    out = []
    for path in sorted(p for p in inbox.iterdir() if p.is_file()):
        if path.name == "README.md" or path.name.endswith(".meta.txt"):
            continue
        meta = {}
        meta_path = path.with_name(path.name + ".meta.txt")
        if meta_path.exists():
            for line in meta_path.read_text(encoding="utf-8").splitlines():
                key, _sep, value = line.partition(":")
                meta[key.strip().lower()] = value.strip()
        data = path.read_bytes()
        out.append({"name": path.name, "size": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                    "listId": meta.get("list-id"), "official": meta.get("official", "").lower() == "yes",
                    "retrieved": meta.get("retrieved")})
    return out


def be_write_manifest(files: list, path: Path = MANIFEST) -> None:
    lines = ["# Inbox manifest (generated by scripts/be_source_inbox.py)", "",
             f"{len(files)} document(s).", "",
             "| File | Size | SHA-256 | DOWNLOAD_LIST id | Official | Retrieved |",
             "|------|------|---------|------------------|----------|-----------|"]
    lines += [f"| {f['name']} | {f['size']} | `{f['sha256']}` | {f['listId'] or '—'} | "
              f"{'yes' if f['official'] else 'no'} | {f['retrieved'] or '—'} |" for f in files]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def be_register_sources(db, files: list, actor_id=None) -> list:
    """Record each file as a SourceArtifact (idempotent by checksum)."""
    from app.modules.payroll.models import SourceArtifact

    out = []
    for f in files:
        existing = db.query(SourceArtifact).filter(SourceArtifact.checksum_sha256 == f["sha256"]).first()
        if existing is not None:
            out.append(existing)
            continue
        title = f"{f['listId'] or 'BE source'}: {f['name']}"
        row = SourceArtifact(agency="Belgian authority (see DOWNLOAD_LIST)",
                             title=(title if f["official"] else f"{title} [UNVERIFIED]")[:300],
                             form_number=f"ZP-BE-SRC-{f['sha256'][:12]}", checksum_sha256=f["sha256"],
                             file_path=str(INBOX / f["name"]) if f["official"] else None,
                             original_filename=f["name"][:255], file_size_bytes=f["size"], created_by_id=actor_id)
        db.add(row)
        db.flush()
        out.append(row)
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--register", action="store_true", help="record the files as source artifacts (local DB)")
    args = parser.parse_args()
    files = be_inbox_files()
    be_write_manifest(files)
    print(f"{len(files)} document(s) in the inbox; manifest written to {MANIFEST}")
    if args.register and files:
        from app.database import SessionLocal, initialize_database
        from scripts._local_db_guard import assert_local_database

        assert_local_database("be_source_inbox")
        initialize_database()
        db = SessionLocal()
        try:
            rows = be_register_sources(db, files)
            db.commit()
            print(f"registered {len(rows)} source artifact(s)")
        finally:
            db.close()


if __name__ == "__main__":
    main()
